<?php
/**
 * WordPress AI Client adapter.
 *
 * @package DevRivo\Chatbot
 */

declare( strict_types=1 );

namespace DevRivo\Chatbot\AI;

use WordPress\AiClient\Messages\DTO\Message;
use WordPress\AiClient\Messages\DTO\MessagePart;
use WordPress\AiClient\Messages\DTO\ModelMessage;
use WordPress\AiClient\Messages\DTO\UserMessage;
use WordPress\AiClient\Providers\Http\DTO\RequestOptions;
use WordPress\AiClient\Results\DTO\GenerativeAiResult;
use WordPress\AiClient\Tools\DTO\FunctionCall;
use WordPress\AiClient\Tools\DTO\FunctionDeclaration;
use WordPress\AiClient\Tools\DTO\FunctionResponse;
use WP_Error;

defined( 'ABSPATH' ) || exit;

/**
 * The only class that calls wp_ai_client_prompt().
 *
 * Follows the spike findings (docs/spikes/ai-client.md): always a provider
 * and model preference, native function declarations, a per-request timeout
 * through using_request_options() (never global filters), history through
 * with_history(), and tool call IDs echoed back exactly as received (Gemini
 * IDs are generated by the client). The model's own message is passed back
 * unchanged in later rounds so provider data (thought signatures) survives.
 * Nothing thrown inside ever escapes: it becomes a WP_Error.
 */
final class WpAiClientAdapter implements AiClientInterface {

	/**
	 * Default reply budget in tokens.
	 */
	public const MAX_TOKENS = 500;

	/**
	 * Default request timeout in seconds.
	 */
	public const TIMEOUT = 20;

	/**
	 * How long a support check is cached (seconds).
	 */
	private const AVAILABLE_TTL = HOUR_IN_SECONDS;

	/**
	 * Generates a reply.
	 *
	 * @param array<string, mixed> $request Request (see AiClientInterface).
	 * @return array{text: string, tool_calls: list<array{id: string, name: string, args: array<string, mixed>}>, usage: array{prompt: int, completion: int, total: int}, provider: string, model: string, message: mixed}|WP_Error
	 */
	public function generate( array $request ): array|WP_Error {
		if ( ! function_exists( 'wp_ai_client_prompt' ) ) {
			return new WP_Error( 'devrivo_chatbot_ai_unavailable', 'The WordPress AI Client is not available.', array( 'status' => 503 ) );
		}

		try {
			$builder = wp_ai_client_prompt()
				->using_provider( (string) $request['provider'] )
				->using_model_preference( (string) $request['model'] )
				->using_system_instruction( (string) ( $request['system'] ?? '' ) )
				->using_max_tokens( (int) ( $request['max_tokens'] ?? self::MAX_TOKENS ) )
				->using_request_options( RequestOptions::fromArray( array( RequestOptions::KEY_TIMEOUT => (float) ( $request['timeout'] ?? self::TIMEOUT ) ) ) );

			$declarations = self::declarations( (array) ( $request['tools'] ?? array() ) );
			if ( array() !== $declarations ) {
				$builder = $builder->using_function_declarations( ...$declarations );
			}

			$result = $builder->with_history( ...self::messages( $request ) )->generate_text_result();
			if ( is_wp_error( $result ) ) {
				return $result;
			}

			return self::to_result( $result );
		} catch ( \Throwable $e ) {
			// The exception message may contain provider details: never pass it on.
			return new WP_Error( 'devrivo_chatbot_ai_exception', 'The AI request failed.', array( 'status' => 500 ) );
		}
	}

	/**
	 * Zero-cost support check with the function declarations, cached for an hour.
	 *
	 * @param string                           $provider Provider ID.
	 * @param string                           $model    Model ID.
	 * @param array<int, array<string, mixed>> $tools    Tool declarations.
	 */
	public function is_available( string $provider, string $model, array $tools = array() ): bool {
		if ( '' === $provider || '' === $model || ! function_exists( 'wp_ai_client_prompt' ) || ! function_exists( 'wp_supports_ai' ) || ! wp_supports_ai() ) {
			return false;
		}

		$key    = 'devrivo_chatbot_ai_ok_' . md5( $provider . '|' . $model . '|' . implode( ',', array_column( $tools, 'name' ) ) );
		$cached = get_transient( $key );
		if ( 'yes' === $cached || 'no' === $cached ) {
			return 'yes' === $cached;
		}

		try {
			$builder = wp_ai_client_prompt( 'ping' )
				->using_provider( $provider )
				->using_model_preference( $model );

			$declarations = self::declarations( $tools );
			if ( array() !== $declarations ) {
				$builder = $builder->using_function_declarations( ...$declarations );
			}

			$available = true === $builder->is_supported_for_text_generation();
		} catch ( \Throwable $e ) {
			$available = false;
		}

		set_transient( $key, $available ? 'yes' : 'no', self::AVAILABLE_TTL );

		return $available;
	}

	/**
	 * Maps an AI Client result to the plain result array.
	 *
	 * @param GenerativeAiResult $result Result.
	 * @return array{text: string, tool_calls: list<array{id: string, name: string, args: array<string, mixed>}>, usage: array{prompt: int, completion: int, total: int}, provider: string, model: string, message: mixed}
	 */
	public static function to_result( GenerativeAiResult $result ): array {
		$message = $result->toMessage();
		$texts   = array();
		$calls   = array();

		foreach ( $message->getParts() as $part ) {
			$call = $part->getFunctionCall();
			if ( null !== $call ) {
				$calls[] = array(
					// Echoed back exactly as received.
					'id'   => (string) $call->getId(),
					'name' => (string) $call->getName(),
					'args' => self::args( $call->getArgs() ),
				);
				continue;
			}

			$text = $part->getText();
			if ( null !== $text && $part->getChannel()->isContent() ) {
				$texts[] = $text;
			}
		}

		$usage = $result->getTokenUsage();

		return array(
			'text'       => trim( implode( "\n", $texts ) ),
			'tool_calls' => $calls,
			'usage'      => array(
				'prompt'     => $usage->getPromptTokens(),
				'completion' => $usage->getCompletionTokens(),
				'total'      => $usage->getTotalTokens(),
			),
			'provider'   => $result->getProviderMetadata()->getId(),
			'model'      => $result->getModelMetadata()->getId(),
			'message'    => $message,
		);
	}

	/**
	 * Conversation as AI Client messages: earlier turns (consecutive turns of
	 * the same role merged, starting with the visitor), the visitor's message,
	 * then this request's tool rounds.
	 *
	 * @param array<string, mixed> $request Request.
	 * @return list<Message>
	 */
	public static function messages( array $request ): array {
		$turns = array();
		foreach ( (array) ( $request['history'] ?? array() ) as $turn ) {
			$role = 'assistant' === ( $turn['role'] ?? '' ) ? 'assistant' : 'user';
			$text = trim( (string) ( $turn['text'] ?? '' ) );
			if ( '' === $text || ( array() === $turns && 'assistant' === $role ) ) {
				continue;
			}
			$turns[] = array( $role, $text );
		}
		$turns[] = array( 'user', (string) ( $request['message'] ?? '' ) );

		$merged = array();
		foreach ( $turns as list( $role, $text ) ) {
			$last = array_key_last( $merged );
			if ( null !== $last && $merged[ $last ][0] === $role ) {
				$merged[ $last ][1] .= "\n\n" . $text;
				continue;
			}
			$merged[] = array( $role, $text );
		}

		$messages = array();
		foreach ( $merged as list( $role, $text ) ) {
			$parts      = array( new MessagePart( $text ) );
			$messages[] = 'assistant' === $role ? new ModelMessage( $parts ) : new UserMessage( $parts );
		}

		foreach ( (array) ( $request['tool_steps'] ?? array() ) as $step ) {
			$original = $step['message'] ?? null;
			if ( $original instanceof Message ) {
				$messages[] = $original;
			} else {
				$messages[] = new ModelMessage(
					array_map(
						static fn( array $call ): MessagePart => new MessagePart( new FunctionCall( $call['id'], $call['name'], $call['args'] ) ),
						(array) ( $step['calls'] ?? array() )
					)
				);
			}

			$messages[] = new UserMessage(
				array_map(
					static fn( array $result ): MessagePart => new MessagePart( new FunctionResponse( $result['id'], $result['name'], $result['response'] ) ),
					(array) ( $step['results'] ?? array() )
				)
			);
		}

		return $messages;
	}

	/**
	 * Function declarations from tool definitions.
	 *
	 * @param array<int, mixed> $tools Tools.
	 * @return list<FunctionDeclaration>
	 */
	private static function declarations( array $tools ): array {
		$declarations = array();
		foreach ( $tools as $tool ) {
			if ( is_array( $tool ) && isset( $tool['name'], $tool['description'] ) ) {
				$declarations[] = new FunctionDeclaration(
					(string) $tool['name'],
					(string) $tool['description'],
					is_array( $tool['parameters'] ?? null ) ? $tool['parameters'] : null
				);
			}
		}

		return $declarations;
	}

	/**
	 * Function call arguments as an array.
	 *
	 * @param mixed $args Arguments from the provider.
	 * @return array<string, mixed>
	 */
	private static function args( mixed $args ): array {
		if ( is_string( $args ) ) {
			$args = json_decode( $args, true );
		} elseif ( is_object( $args ) ) {
			$args = json_decode( (string) wp_json_encode( $args ), true );
		}

		return is_array( $args ) ? $args : array();
	}
}
